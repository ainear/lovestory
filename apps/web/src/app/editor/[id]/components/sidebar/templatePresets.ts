import type { CanvasElement, CanvasSection } from "../useCanvasReducer";

export interface TemplatePreset {
  slug: string;
  label: string;
  emoji: string;
  category: "romantic" | "modern" | "classic" | "minimal";
  background: string;
  sections: CanvasSection[];
  elements: CanvasElement[];
  accent: string; // for thumbnail border
}

// Helper to create unique IDs
let _uid = 0;
function uid() {
  return `tpl_${Date.now()}_${++_uid}`;
}

// ── Shared text factory ──
type TextTransformType = "none" | "uppercase" | "capitalize" | "lowercase";
type TextShadowType = {
  active: boolean;
  color: string;
  blur: number;
  x: number;
  y: number;
};
 
function txt(
  sId: string,
  x: number,
  y: number,
  w: number,
  h: number,
  z: number,
  text: string,
  fontSize: number,
  fontFamily: string,
  color: string,
  opts?: Record<string, any>,
): CanvasElement {
  const textTransform: TextTransformType = opts?.textTransform ?? "none";
  const textShadow: TextShadowType = opts?.textShadow ?? {
    active: false,
    color: "#000",
    blur: 0,
    x: 0,
    y: 0,
  };
  return {
    id: uid(),
    sectionId: sId,
    type: "text",
    x,
    y,
    width: w,
    height: h,
    rotation: 0,
    opacity: opts?.opacity ?? 1,
    zIndex: z,
    locked: false,
    props: {
      text,
      fontSize,
      fontFamily,
      color,
      textAlign: "center",
      fontWeight: opts?.fontWeight ?? "normal",
      fontStyle: opts?.fontStyle ?? "normal",
      textDecoration: "none",
      lineHeight: opts?.lineHeight ?? 1.4,
      letterSpacing: opts?.letterSpacing ?? 0,
      textTransform,
      textShadow,
      backgroundColor: "",
    },
  };
}
function wgt(
  sId: string,
  x: number,
  y: number,
  w: number,
  h: number,
  z: number,
  props: Record<string, unknown>,
): CanvasElement {
  return {
    id: uid(),
    sectionId: sId,
    type: "widget",
    x,
    y,
    width: w,
    height: h,
    rotation: 0,
    opacity: 1,
    zIndex: z,
    locked: false,
    props,
  };
}

